"""EXPLORATORY / POST HOC: the exploratory pay screen (not a theorem) for sparse
prefill (`attnbench.exploratory.pay_bound`), checked on every sparse
cell of P2 and P4 (the researcher's paper-quality wave of 28 Nov 2026,
item 11). Nothing is scored, nothing is fitted, nothing is measured.

    python3 scripts/pay_bound.py --inputs <inputs.json> --mirror <dir> \\
        --banked <attnbench_backups dir> --out-dir docs/paper/exploratory

Inputs per sparse cell: the traced device-busy time B (mean over the cell's
ground-truth traces, `exploratory_residual.device_busy`), the pairing's
bare-timed null-kernel launch floor f (the cell's `bare_prices.json`), the
counts of issued operations and in-step synchronisations (the committed
priced sequence), and the measured medians of the sparse cell and of the
dense cell at the same length and batch (as scored). P3 is left out: its
ground-truth traces are not read by this wave's loaders.
"""

from __future__ import annotations

import argparse
import glob
import json
import statistics
import sys
import warnings
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import exploratory_residual as ER  # noqa: E402
import exploratory_wave as EW  # noqa: E402
import null_kernel_bias as NKB  # noqa: E402
from attnbench.exploratory import pay_bound as PB  # noqa: E402

TRACES = {
    "P2": "bucket_tierA_20261121/attnbench-a100-p2e-20261114-0546/results/"
          "t61_p2_20261114T0022Z/12_ground_truth/eager/traces/trace_*.json",
    "P4": "p4_traces_20261116/*/results/*/trace_*.json",
}


def pairing(D, p: str, banked: Path) -> dict:
    cp, ms = D["cps"][p], D["ms"][p]
    files = sorted(glob.glob(str(banked / TRACES[p])))
    if not files:
        raise SystemExit(f"{p}: no ground-truth trace under --banked")
    recs = EW.extract(cp, files)
    busy_of = {Path(f).name: ER.device_busy(f) for f in files}
    busy = {}
    for r in recs:
        busy.setdefault(r["key"], []).append(busy_of[r["trace"]])
    dense = {(c.context_length, c.batch): c for c in cp.cells if c.arm == "dense"}
    rows, untraced = [], []
    for c in sorted(cp.cells, key=lambda c: (c.context_length, c.batch, c.arm, c.density)):
        if c.arm == "dense":
            continue
        if c.key not in busy:
            untraced.append(NKB.cell_name(c))
            continue
        d = dense[(c.context_length, c.batch)]
        bp = json.loads((NKB.cell_dir(banked / NKB.HOST[p], c) / "bare_prices.json").read_text())
        n = PB.counts(c.priced)
        b = statistics.fmean(busy[c.key])
        lb = PB.lower_bound(b, bp["launch_floor_s"], n["ops"], n["in_step_syncs"])
        chain = float(sum(c.priced.device) + sum(c.priced.link))
        lbp = PB.lower_bound(chain, bp["launch_floor_s"], n["ops"], n["in_step_syncs"])
        rows.append({"cell": NKB.cell_name(c), "arm": c.arm, "busy_s": b,
                     "floor_s": bp["launch_floor_s"], **n, **lb,
                     "sparse_s": ms["seconds"][c.key], "dense_s": ms["seconds"][d.key],
                     "verdict": PB.verdict(lb["lb_s"], ms["seconds"][d.key]),
                     "priced_chain_s": chain, "lb_priced_s": lbp["lb_s"],
                     "verdict_priced": PB.verdict(lbp["lb_s"], ms["seconds"][d.key]),
                     "measured": "win" if ms["seconds"][c.key] < ms["seconds"][d.key] else "loss"})
    return {"rows": rows, "untraced": untraced, "check": PB.check(rows),
            "check_priced": PB.check(rows, "lb_priced_s")}


def to_markdown(o: dict) -> str:
    L = ["# EXPLORATORY / POST HOC: an exploratory screen for when sparse prefill cannot pay "
         "(28 Nov 2026)", "",
         "**EXPLORATORY / POST HOC. Nothing is scored; no parameter is fitted on P1–P4; "
         "nothing is measured.** Generated by `scripts/pay_bound.py`; numbers in "
         "`pay_bound.json`. The construction is in `attnbench/exploratory/pay_bound.py`.", "",
         "**A screen, not a theorem.** It rests on stated assumptions (one stream, in-order "
         "issue, and the bare-timed null kernel's mean as the least issue cost per operation), "
         "and f is itself a measured mean, so the bound can fail on a cell; it was built and "
         "checked on the same banked cells, after the fact.", "",
         "A sparse cell can pay only if LB = max(B + n_sync·f, N·f) < T_dense, with B the "
         "traced device-busy time, f the bare-timed null-kernel launch floor, N the issued "
         "operations and n_sync the in-step synchronisations.", "",
         "| pairing | B read from | sparse cells | measured wins | violations | losses ruled out | "
         "LB above measured sparse | median T_sparse / LB | min |",
         "|---|---|---|---|---|---|---|---|---|"]
    for p in ("P2", "P4"):
        for lab, key in (("traced", "check"), ("priced (before timing)", "check_priced")):
            k = o[p][key]
            L.append(f"| {p} | {lab} | {k['cells']} | {k['measured_wins']} | {k['violations']} | "
                     f"{k['losses_ruled_out']} of {k['measured_losses']} | "
                     f"{k['floor_above_measured_sparse']} | {k['slack_median']:.2f} | "
                     f"{k['slack_min']:.2f} |")
    L += ["", f"**Verdict: {o['verdict']}**", ""]
    for p in ("P2", "P4"):
        L += [f"## {p}", "", "| cell | B traced ms | B priced ms | f µs | N | n_sync | LB ms | "
              "LB priced ms | binds | sparse ms | dense ms | condition | condition (priced) | "
              "measured |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in o[p]["rows"]:
            L.append(f"| {r['cell']} | {r['busy_s']*1e3:.1f} | {r['priced_chain_s']*1e3:.1f} | "
                     f"{r['floor_s']*1e6:.2f} | {r['ops']} | "
                     f"{r['in_step_syncs']} | {r['lb_s']*1e3:.1f} | {r['lb_priced_s']*1e3:.1f} | "
                     f"{r['binding']} | {r['sparse_s']*1e3:.1f} | {r['dense_s']*1e3:.1f} | "
                     f"{r['verdict']} | {r['verdict_priced']} | {r['measured']} |")
        if o[p]["untraced"]:
            L += ["", "No ground-truth trace: " + ", ".join(o[p]["untraced"]) + "."]
        L.append("")
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--inputs", required=True, type=Path)
    ap.add_argument("--mirror", required=True, type=Path)
    ap.add_argument("--banked", required=True, type=Path)
    ap.add_argument("--out-dir", required=True, type=Path)
    a = ap.parse_args(argv)
    warnings.filterwarnings("ignore")
    D = EW.load(a.inputs, a.mirror)
    out = {"label": PB.LABEL, "task": "paper-quality wave, 28 Nov 2026, item 11"}
    for p in ("P2", "P4"):
        out[p] = pairing(D, p, a.banked)
    ks = [out[p][k] for p in ("P2", "P4") for k in ("check", "check_priced")]
    sep = any(k["separates_any"] for k in ks)
    bad = sum(k["violations"] for k in ks)
    out["verdict"] = ("violated on banked data: the screen fails as measured" if bad else
                      "kept as an exploratory screen: held on every banked cell and "
                      "separates at least one measured loss" if sep else
                      "held on every banked cell but too loose to separate any cell: dropped")
    text, md = json.dumps(out, indent=1, default=str), to_markdown(out)
    bucket = json.loads(a.inputs.read_text())["bucket"]
    EW.refuse_store(text, bucket)
    EW.refuse_store(md, bucket)
    a.out_dir.mkdir(parents=True, exist_ok=True)
    (a.out_dir / "pay_bound.json").write_text(text + "\n")
    (a.out_dir / "pay_bound.md").write_text(md)
    print(out["verdict"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
