"""Every number the paper's text cites, as `numbers.json` and as LaTeX
macros in `numbers.tex` (C10).

A number is named by what it is of: the quantity, then the predictor, model,
code path and result class it belongs to. The macro is that name in
CamelCase letters only (LaTeX allows no digits in a command name; digits are
spelled out), prefixed `\\ab`. Code path labels are hashes, so each is given
a letter in sorted order (`CodePathA`, ...) and `numbers.json` maps the
letter to the label. Two numbers with one macro are refused, never
renamed.

Values are kept at full precision in the JSON; the macro holds the text
form: a fraction as a percentage to two decimals (the text writes the
percent sign), a time in seconds to four decimals, a count as an integer.
Rule 1: no number here says "no accuracy loss"; these are times and errors.
"""

from __future__ import annotations

import re
import statistics
from typing import Mapping, Optional, Sequence

from ..predict import scoring as SC
from . import paper_tables as PT
from .paper_inputs import CLASSES, Inputs, PaperInputError

UNITS = ("fraction", "seconds", "count", "launches")
_DIGITS = ("Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine")


def _letters(n: int) -> str:
    s = ""
    n += 1
    while n:
        n, r = divmod(n - 1, 26)
        s = chr(65 + r) + s
    return s


def camel(part) -> str:
    s = str(part).replace(".", " point ").replace("+", " plus ").replace("-", " minus ")
    s = re.sub(r"\d", lambda m: " " + _DIGITS[int(m.group())] + " ", s)
    words = re.split(r"[^A-Za-z]+", s)
    return "".join(w[:1].upper() + w[1:] for w in words if w)


def tex_value(value, unit: str) -> str:
    if unit == "fraction":
        return f"{100 * value:.2f}"
    if unit == "seconds":
        return f"{value:.4f}"
    if unit in ("count", "launches"):
        if isinstance(value, bool) or int(value) != value:
            raise PaperInputError(f"a {unit} is an integer, got {value!r}")
        return str(int(value))
    raise PaperInputError(f"unit {unit!r} is not one of {UNITS}")


class Numbers:
    def __init__(self, inp: Inputs):
        self.inp = inp
        cps = sorted({c.code_path for c in inp.cp.cells})
        self.code_paths = {cp: "CodePath" + _letters(i) for i, cp in enumerate(cps)}
        self.entries: dict = {}

    def add(self, quantity: str, value, unit: str, *, predictor: Optional[str] = None,
            model: Optional[str] = None, code_path: Optional[str] = None,
            result_class: Optional[str] = None, extra: Sequence = ()) -> str:
        if result_class is not None and result_class not in CLASSES:
            raise PaperInputError(f"result class {result_class!r}")
        parts = [quantity, predictor, model,
                 None if code_path is None else self.code_paths[code_path],
                 result_class, *extra]
        name = "ab" + "".join(camel(p) for p in parts if p is not None)
        if name in self.entries:
            raise PaperInputError(f"two numbers named \\{name}")
        of = {k: v for k, v in (("predictor", predictor), ("model", model),
                                ("code_path", code_path), ("result_class", result_class))
              if v is not None}
        if extra:
            of["extra"] = list(extra)
        self.entries[name] = {"quantity": quantity, "of": of, "value": value, "unit": unit,
                              "tex": tex_value(value, unit)}
        return name

    def tex(self) -> str:
        lines = ["% Generated by scripts/paper_artifacts.py; do not edit.",
                 f"% prediction sha256 {self.inp.cp.sha256}"]
        lines += [f"\\newcommand{{\\{n}}}{{{e['tex']}}}" for n, e in sorted(self.entries.items())]
        return "\n".join(lines) + "\n"


def collect(inp: Inputs, decision: Sequence[PT.DecisionGroup],
            crossover: Optional[Sequence[PT.CrossoverSeries]]) -> Numbers:
    N = Numbers(inp)
    N.add("relative noise floor", inp.relative_floor, "fraction")
    N.add("resolution floor", inp.resolution_floor_s, "seconds")
    N.add("queue depth", inp.cp.queue_depth, "launches")
    N.add("committed cells", len(inp.cp.cells), "count")
    N.add("measured cells", len(inp.measured), "count")

    for r in PT.predictor_rows(inp):
        kw = dict(predictor=r["predictor"], model=r["model"], code_path=r["code_path"],
                  result_class=r["result_class"])
        N.add("cells", r["n"], "count", **kw)
        N.add("cells inside floor", r["n_inside_floor"], "count", **kw)
        N.add("median abs error", r["median_abs_relative"], "fraction", **kw)
        N.add("mean error", r["mean_relative"], "fraction", **kw)
        N.add("max abs error", r["max_abs_relative"], "fraction", **kw)

    for r in PT.sync_rows(inp):
        N.add("median abs error", r["median_abs_relative"], "fraction",
              predictor=r["predictor"], model=r["model"], code_path=r["code_path"],
              result_class=r["result_class"],
              extra=("syncs", r["n_synchronisations"]))

    abl: dict = {}
    for r in PT.ablation_rows(inp):
        abl.setdefault((r["key"].model, r["key"].code_path, r["result_class"]), []).append(r)
    for (model, cpath, cls), rs in sorted(abl.items()):
        kw = dict(model=model, code_path=cpath, result_class=cls)
        for a in PT.ABLATIONS:
            N.add("median abs error", statistics.median(abs(r[f"{a}_relative"]) for r in rs),
                  "fraction", predictor=a, **kw)
        N.add("cells with a bound above measured",
              sum(bool(r["bound_above_measured"]) for r in rs), "count", **kw)

    q: dict = {}
    for r in PT.queue_rows(inp):
        q.setdefault((r["key"].model, r["key"].code_path, r["result_class"]), []).append(r)
    for (model, cpath, cls), rs in sorted(q.items()):
        kw = dict(predictor="recursion", model=model, code_path=cpath, result_class=cls)
        for i, (m, _, _) in enumerate(rs[0]["points"]):
            tag = "no queue" if m is None else f"{m:g}x"
            N.add("max abs queue change", max(abs(r["points"][i][2]) for r in rs), "fraction",
                  extra=(tag,), **kw)
        flips = [r for r in rs if r["flips_at"] is not None]
        if flips:
            N.add("cells whose sign flips", sum(bool(r["flips_at"]) for r in flips), "count",
                  **kw)

    for g in decision:
        kw = dict(predictor=g.predictor, model=g.model, code_path=g.code_path,
                  result_class=g.result_class)
        d = g.scored.decision
        N.add("decision scored", g.scored.n_scored, "count", **kw)
        N.add("decision correct", d[SC.CORRECT], "count", **kw)
        N.add("decision false profitable", d[SC.FALSE_PROFITABLE], "count", **kw)
        N.add("decision missed profitable", d[SC.MISSED_PROFITABLE], "count", **kw)
        N.add("sign agrees", g.scored.sign_agree, "count", **kw)
        N.add("sign disagrees", g.scored.sign_disagree, "count", **kw)
        N.add("decision inside floor", len(g.scored.inside_floor), "count", **kw)

    if crossover:
        cx: dict = {}
        for s in crossover:
            cx.setdefault((s.predictor, s.series[0], s.series[1], s.result_class), []).append(s)
        for (pred, model, cpath, cls), ss in sorted(cx.items()):
            kw = dict(predictor=pred, model=model, code_path=cpath, result_class=cls)
            N.add("crossover series", len(ss), "count", **kw)
            comps = [c for s in ss for c in s.error.comparisons]
            N.add("crossover brackets compared", len(comps), "count", **kw)
            N.add("crossover measured inside predicted", sum(c.contains for c in comps),
                  "count", **kw)
            N.add("crossover direction agrees", sum(c.direction_agrees for c in comps),
                  "count", **kw)
    return N


def as_json(N: Numbers, *, extra: Mapping) -> dict:
    return {**extra, "code_paths": {v: k for k, v in N.code_paths.items()},
            "result_classes": dict(CLASSES), "numbers": N.entries}
